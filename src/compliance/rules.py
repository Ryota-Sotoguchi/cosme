"""NG表現の辞書。

## 発信ジャンル（2026-09-14 に「コスメ・美容」→「転職・年収・キャリア」へ変更）

化粧品向けのルール（1・6）は、休止中の商品投稿（楽天）を守るために残している。
ただし転職の文章で誤検知する語は、肌・髪・効果の文脈に限定した
（「待遇改善」「一生もののスキル」「クリニックへの転職」「医薬品業界」を止めない）。
転職ジャンルで起きる問題は 7〜11 に置く。

出典の考え方:
  * 薬機法 / 化粧品等の適正広告ガイドライン
      一般化粧品で標ぼうできる効能効果は56項目に限定される。
      「改善」「修復」「促進」「根本的に」などは使えない。
      そもそもこのアカウントは効能を語らず客観情報だけを扱うため、
      効能表現が出てきた時点で設計違反として弾く。
  * 景品表示法（ステマ規制, 2023-10-01施行）
      アフィリエイトリンクを含む投稿は広告と判別できる表示が必要。
  * 商品ページに書いてある文言でも、そのままSNS広告へ転用できるとは限らない前提で判定する。

安全側に倒す。迷う表現は落とす。
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Rule:
    category: str
    pattern: re.Pattern[str]
    label: str


def _rule(category: str, label: str, pattern: str) -> Rule:
    return Rule(category=category, label=label, pattern=re.compile(pattern))


