"""NG表現の辞書。

出典の考え方:
  * 薬機法 / 化粧品等の適正広告ガイドライン
      一般化粧品で標ぼうできる効能効果は56項目に限定される。
      「改善」「修復」「促進」「根本的に」などは使えない。
      そもそもこのアカウントは効能を語らず客観情報だけを扱うため、
      効能表現が出てきた時点で設計違反として弾く。
  * 景品表示法（ステマ規制, 2023-10-01施行）
      アフィリエイトリンクを含む投稿は広告と判別できる表示が必要。
  * 商品ページに書いてある文言でも、そのままSNS広告へ転用できるとは限らない前提で判定する。

安全側に倒す。迷う表現は落とす。
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Rule:
    category: str
    pattern: re.Pattern[str]
    label: str


def _rule(category: str, label: str, pattern: str) -> Rule:
    return Rule(category=category, label=label, pattern=re.compile(pattern))


# ======================================================================
# 1. 薬機法（効能効果・治療表現）
# ======================================================================
MEDICAL_RULES: tuple[Rule, ...] = (
    _rule("medical", "治癒・治療表現", r"(治る|治す|治療|完治|快方|根治|治り)"),
    _rule("medical", "消失表現", r"(シミ|しみ|シワ|しわ|毛穴|ニキビ|にきび|くすみ|たるみ)[^。！？\n]{0,8}(が|は|も)?[^。！？\n]{0,6}(消え|消す|なくな|取れ|除去)"),
    _rule("medical", "改善・修復表現", r"(改善|修復|再生|活性化|細胞|真皮|角質層を超|浸透して.{0,6}(治|再生))"),
    _rule("medical", "若返り表現", r"(若返|アンチエイジング|老化を?(防|止)|エイジングケアで.{0,6}(改善|回復))"),
    _rule("medical", "美白・医療的表現", r"(美白効果|漂白|ホワイトニング効果|シミが薄く|色素を分解)"),
    _rule("medical", "発毛・育毛表現", r"(発毛|育毛|養毛|毛が生え|薄毛が)"),
    # 「やせ」だけで拾うと「増やせば」「冷やせば」まで誤検知するので、
    #  痩身の意味になる語形に絞る。
    _rule("medical", "痩身表現", r"(痩せ|痩身|ヤセ|やせる|やせた|やせて|やせ体質|脂肪を?燃焼|セルライトが?(消|減)|デトックス)"),
    _rule("medical", "医療関与の示唆", r"(医師|皮膚科医|専門医|ドクター)[^。！？\n]{0,10}(推奨|監修|認め|保証|お墨付き)"),
    _rule("medical", "肌質変化の断定", r"(肌質が変わ|肌が生まれ変わ|体質が変わ)"),
    _rule("medical", "症状名への言及", r"(アトピー|アレルギーが|敏感肌が治|皮膚炎|湿疹)"),
)

# ======================================================================
# 2. 効果・安全性の保証、断定
# ======================================================================
GUARANTEE_RULES: tuple[Rule, ...] = (
    _rule("guarantee", "絶対表現", r"(絶対に?(効|荒れ|大丈夫|安全)|必ず(効|良く|きれい)|100%|１００%|確実に効)"),
    _rule("guarantee", "誰にでも表現", r"(誰でも|どんな肌でも|全ての人に|万人に)[^。！？\n]{0,10}(効|合う|使える|安心)"),
    _rule("guarantee", "無害・安全の断定", r"(完全に安全|副作用[はもがのな]{0,2}(ない|なし|あり(ません|得ない))|絶対に安心|刺激ゼロ|無害)"),
    _rule("guarantee", "永続性の断定", r"(ずっと(続く|持続)|永久に|一生もの)"),
    _rule("guarantee", "即効性の断定", r"(即効|すぐに(効|変わ)|使った(翌日|瞬間)から)"),
)

# ======================================================================
# 3. 架空の使用体験（このアカウントの絶対禁止事項）
# ======================================================================
EXPERIENCE_RULES: tuple[Rule, ...] = (
    _rule("experience", "使用体験", r"(使ってみた|使ってみて|使ってる|使用してみ|試してみた|塗ってみた|つけてみた)"),
    _rule("experience", "愛用・リピート", r"(愛用|リピ(ート)?(確定|決定|してる|中)|常備してる|手放せない|定番になった)"),
    _rule("experience", "購入体験", r"(買ってよかった|買って正解|届いた|注文した|購入しました|ポチった|レビューします)"),
    _rule("experience", "身体変化の主張", r"(肌が変わ|肌荒れが(治|落ち着|なくな)|もちもちに|つるつるに|ふっくら)"),
    _rule("experience", "一人称の肌言及", r"(私の肌|自分の肌|うちの肌|わたしの肌)"),
    _rule("experience", "感想の断定", r"(お気に入り(です|でした)|大満足|感動した|めちゃくちゃ良かった|最高でした)"),
)

# ======================================================================
# 4. 架空の口コミ・第三者の声（取得していないデータを語らない）
# ======================================================================
FAKE_REVIEW_RULES: tuple[Rule, ...] = (
    _rule("fake_review", "口コミ内容の創作", r"(口コミ(では|によると|で(は)?評判|多数)|レビューでは.{0,10}(という|との)声)"),
    _rule("fake_review", "第三者の声の創作", r"(みんな|多くの人が|話題に?なって|SNSで(人気|話題|バズ)|愛用者が)"),
    _rule("fake_review", "評判の主張", r"(評判が(いい|良い|高い)|好評(です|らしい)|支持されて)"),
    _rule("fake_review", "リピーター主張", r"(リピーターが多い|何度も買われて|売れ続けて)"),
)

# ======================================================================
# 5. 誇張・根拠のないランキング
# ======================================================================
EXAGGERATION_RULES: tuple[Rule, ...] = (
    _rule("exaggeration", "No.1表現", r"(No\.?\s?1|NO\.?\s?1|ナンバーワン|第1位|第一位|1位獲得|売上1位|人気1位)"),
    _rule("exaggeration", "最上級表現", r"(最高の|最強|最安値|日本一|世界一|唯一無二|究極の|奇跡の|神アイテム|バズ)"),
    _rule("exaggeration", "煽り表現", r"(絶対に買うべき|買わないと損|見逃し厳禁|今すぐ買|急いで|残りわずか|在庫僅少|完売間近)"),
    _rule("exaggeration", "効果の誇張", r"(劇的に|圧倒的に(効|変わ)|見違える|別人のよう)"),
)

# ======================================================================
# 6. 医薬品・医薬部外品など、扱わないカテゴリー
# ======================================================================
CATEGORY_RULES: tuple[Rule, ...] = (
    _rule("category", "医薬品への言及", r"(医薬品|第1類|第一類|第2類|第二類|第3類|第三類|処方箋|市販薬)"),
    _rule("category", "医薬部外品への言及", r"(医薬部外品|薬用)"),
    _rule("category", "サプリ・健康食品", r"(サプリメント|サプリ|健康食品|機能性表示食品|特定保健用食品|トクホ)"),
    _rule("category", "美容医療", r"(美容外科|美容皮膚科|クリニック|レーザー|注入|ボトックス|ヒアルロン酸注射)"),
)

ALL_RULES: tuple[Rule, ...] = (
    *MEDICAL_RULES,
    *GUARANTEE_RULES,
    *EXPERIENCE_RULES,
    *FAKE_REVIEW_RULES,
    *EXAGGERATION_RULES,
    *CATEGORY_RULES,
)


def scan(text: str) -> list[Rule]:
    """本文に一致したルールをすべて返す。"""
    return [rule for rule in ALL_RULES if rule.pattern.search(text)]
