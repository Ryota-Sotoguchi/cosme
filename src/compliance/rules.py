# ======================================================================
# リンクの有無で適用範囲を分ける
# ======================================================================
# 規制の根拠が違うので、一律に適用すると必要のないところまで縛ることになる。
#
# ## 常に適用するもの（ALWAYS_RULES）
#
# 薬機法66条は **何人も** 規制で、しかも「広告し、記述し、又は流布して
# はならない」と書かれている。広告でなくても、化粧品の効能について
# 虚偽・誇大なことを書けば対象になる。リンクの有無は関係ない。
#
# 取扱い外カテゴリー（医薬品・医薬部外品・美容医療など）も常に止める。
# これは法規制というより、このアカウントが扱わないと決めた範囲。
#
# ## リンク投稿にだけ適用するもの（LINK_ONLY_RULES）
#
# 景品表示法とステマ規制は「事業者が自己の供給する商品について行う表示」
# が対象。リンクの無い投稿は商品を売っていないので、優良誤認も有利誤認も
# 成立しない。
#
# 加えて、うちのリンクなし投稿は **商品名を一切出さない設計** になっている
# （no_link / casual / howto はいずれも商品データを持たない）。
# そのため薬機法の広告該当性3要件のうち「特定商品名が明らかにされている」
# を満たさない。
#
# よってリンクなし投稿では、体験・口コミ・誇張の各ルールを外す。
# ここを縛っていたせいで、雑談で「使ってる」「お気に入り」と書くことすら
# できなくなっていた。
ALWAYS_RULES: tuple[Rule, ...] = (
    *MEDICAL_RULES,      # 薬機法66条（何人も規制）
    *GUARANTEE_RULES,    # 同上。効能の保証・断定
    *CATEGORY_RULES,     # 取扱い外カテゴリー
    # 転職ジャンル。読んだ人の判断を誤らせるものは、リンクの有無に関係なく止める。
    *CAREER_GUARANTEE_RULES,
    *STATISTIC_RULES,
    *SOLICITATION_RULES,
    *DISCRIMINATION_RULES,
    *LEGAL_RULES,
)

LINK_ONLY_RULES: tuple[Rule, ...] = (
    *EXPERIENCE_RULES,   # 使用体験。リンク先商品について語れないだけ
    *FAKE_REVIEW_RULES,  # 口コミの創作。景表法（優良誤認）
    *EXAGGERATION_RULES, # No.1・最上級・煽り。景表法（優良誤認・有利誤認）
)


def scan(text: str, *, has_link: bool = True) -> list[Rule]:
    """本文に一致したルールを返す。

    has_link=False のときは、リンク投稿にだけ必要なルールを外す。
    既定は True。呼び出し側が明示しなければ全部かける（安全側）。
    """
    pool = ALL_RULES if has_link else ALWAYS_RULES
    return [rule for rule in pool if rule.pattern.search(text)]
