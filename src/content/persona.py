"""「中の人」の設定。

## なぜ要るのか

つぶやき85件を数えたら、一人称は6件、暮らしの具体は7件しかなかった。
**毎回別の人が書いている状態**で、それが「誰のアカウントでもない」
感じにつながっていた。

軽い設定を1か所に置いて、そこからはみ出さないようにする。

## 商品の話ではない

ここで決めるのは生活の話で、商品の使用体験ではない。
「詰め替え買い忘れて焦ってる」と同じ種類のことしか書かない。

  ○ 洗面所が暗い / 朝が弱い / ドライヤーが古い
  × この化粧水がしっとりした（使用体験の捏造）
  × 乾燥肌が治った（薬機法）

「乾燥肌」は肌質の自己申告で、商品の効果の話ではないので書いてよい。
ただし**商品と結びつけない**（「これで乾燥が治った」は書かない）。

## 矛盾させない

一度決めたら守る。「一人暮らし」と書いた翌日に「家族で使う」と
書くと、読んでいる側は気づく。テストで固定してある。
"""

from __future__ import annotations

# 設定。**増やすときは矛盾しないか確かめること。**
TRAITS: dict[str, str] = {
    "肌質": "乾燥しやすい",
    "住まい": "一人暮らし",
    "朝": "弱い。支度はいつもぎりぎり",
    "洗面所": "暗い。色が見えにくい",
    "ドライヤー": "古い。乾かすのに時間がかかる",
    "買い方": "迷って何日も見てから決める",
}

# 一人称はこれに統一する。ぶれると別人に見える。
FIRST_PERSON = "わたし"

# 設定と食い違う語。つぶやきに出てきたら矛盾している。
#
#   一人暮らしなのに「家族で」「実家の」
#   乾燥肌なのに「脂性肌だから」
#
# **テストがこれを使って全プールを走査する。**
CONTRADICTIONS: dict[str, tuple[str, ...]] = {
    "一人暮らし": ("家族で使う", "家族の分", "実家の", "夫", "妻", "子ども", "娘", "息子"),
    "乾燥しやすい": ("脂性肌", "オイリー肌だから", "テカりやすいから"),
    "朝が弱い": ("朝型なので", "早起きが得意"),
}


def contradicts(text: str) -> list[str]:
    """設定と食い違う語を返す。無ければ空。"""
    hits = []
    for trait, words in CONTRADICTIONS.items():
        for word in words:
            if word in text:
                hits.append(f"{trait}↔{word}")
    return hits
