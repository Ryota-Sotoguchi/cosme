def tool_benefit_for(item_name: str) -> Benefit | None:
    """商品名から「どんな道具か」を判定する。判定できなければ None。"""
    name = item_name or ""
    for benefit in TOOL_BENEFITS:
        if any(keyword in name for keyword in benefit.keywords):
            return benefit
    return None


def tool_benefit_by_cursor(cursor: int) -> Benefit:
    return TOOL_BENEFITS[cursor % len(TOOL_BENEFITS)]


