"""仕事の道具（手帳・ノート・バッグ）の投稿データ。

## なぜ本と分けるのか

本（`books.py`）は中身を読んでいないので「この種類の本はここを見て選ぶ」までしか
書けなかった。**道具は違う。** レビューの件数が桁違いに多く
（2026-10-28 の実測で手帳のレビュー中央87件。本は4件）、
**使った人が書いた使い勝手を、誰の感想か分かる形で引用できる**。

`voices.py` の `TOOL_WORDS` がその語彙で、`voice_sentence()` が
「書きやすいって書いてる人が多かった」の形にする。
これが本の投稿に無かった «使ってどうなったか» にあたる。

## 守ること

* **こちらが使った体にしない。** 出すのは「使った人はこう書いている」まで
  （CLAUDE.md §4。`rules.py` の体験談ルールが機械的に止める）
* **成果の話にしない。** 「これで仕事がはかどる」は使った人の解釈で裏が取れない。
  出すのは手に取ったときの手触りだけ（`TOOL_WORDS` がその境界）
* 中の人は転職2回の会社員。**道具の専門家ではない**ので、選び方の目線で書く
"""

