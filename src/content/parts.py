# 時間帯。スロットの時刻から決まる。
MORNING, NOON, EVENING, NIGHT = "朝", "昼", "夕", "夜"

# config.toml の [[schedule]] と対応させること。
# 枠を足したらここにも足す（漏れると time_band が空になり、制限が効かない）。
_SLOT_BANDS: dict[str, str] = {
    "morning": MORNING,      # 07:30
    "midmorning": MORNING,   # 09:30
    "latemorning": MORNING,  # 11:00
    "noon": NOON,            # 12:15
    "afternoon": NOON,       # 14:30
    "predinner": EVENING,    # 16:30
    "evening": EVENING,      # 18:00
    "earlynight": EVENING,   # 19:00
    "night": NIGHT,          # 20:30
    "late": NIGHT,           # 22:30
}


def time_band_for(slot: str) -> str:
    """スロット名から時間帯を引く。知らない枠なら空（制限しない）。"""
    return _SLOT_BANDS.get(slot, "")


def time_band_at(hour: int) -> str:
    """**実際に投稿する時刻**から時間帯を引く。

    GitHub Actions の定期実行は大きく遅れる。実測（2026-09-05〜07）では
    ずれの中央値が232分で、90分以内に出た投稿は30本中0本だった。
    枠の名前（morning）で言い回しを選ぶと、朝の枠が夕方に出たときに
    「朝の支度」の話が夕方に流れる。

    枠は「その日に何を出すか」の計画として使い、
    言い回しの時間帯は実際の時刻から引く。
    """
    if 5 <= hour < 11:
        return MORNING
    if 11 <= hour < 16:
        return NOON
    if 16 <= hour < 20:
        return EVENING
    return NIGHT


# ======================================================================
# 日付のタグ
#
# 人が投稿するのは「今日これがあった」から。
# いまの投稿には occasion（投稿する理由）が無く、
# 曜日への言及は85件中2件しかなかった。
#
# タグは重なってよい（金曜かつ月末、など）。
# ======================================================================
MONDAY, FRIDAY, WEEKEND = "月曜", "金曜", "週末"
BEFORE_HOLIDAY = "連休前"
MONTH_END = "月末"
SEASON_TURN = "季節の変わり目"
DRY_SEASON, HUMID_SEASON = "乾燥の時期", "湿気の時期"


def day_tags_for(today: "date") -> tuple[str, ...]:
    """その日に付くタグを全部返す。

    曜日・月末・季節を重ねて返すので、
    「金曜かつ月末」の日には両方のつぶやきが候補になる。
    """
    tags: list[str] = []
    weekday = today.weekday()  # 月=0

    if weekday == 0:
        tags.append(MONDAY)
    elif weekday == 4:
        tags.append(FRIDAY)
    if weekday >= 5:
        tags.append(WEEKEND)

    # 金曜と、土曜（日曜も休みなら連休）の前日
    if weekday in (4, 5):
        tags.append(BEFORE_HOLIDAY)

    if today.day >= 25:
        tags.append(MONTH_END)

    month = today.month
    if month in (3, 6, 9, 12):
        tags.append(SEASON_TURN)
    if month in (11, 12, 1, 2, 3):
        tags.append(DRY_SEASON)
    if month in (6, 7, 8):
        tags.append(HUMID_SEASON)

    return tuple(tags)


def thread_part(part_id: str, *segments: str) -> Part:
    """連投パーツを作る。

    1本目だけがタイムラインに出るので、そこで完結させない。
    「で、どういうこと？」と思わせて2本目に進ませる。
    """
    return Part(part_id, "\n\n".join(segments), segments=tuple(segments))


