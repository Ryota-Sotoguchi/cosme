# リンク投稿の前振り
#
# リンクの無い投稿は「どう思う？」と問いかけてよいが、
# リンク投稿でそれをやると、薦めたいのか意見がほしいのか分からなくなる。
# ここは**薦める側の温度感**で書く。
#
# ただし「この商品が良い」とは書かない。使っていないし、値段やレビューも
# 本文から外したので、良し悪しの主張は根拠を持たない。
# 書けるのは「こういう条件で探すならこれ」という提示まで。
# ======================================================================
# リンク投稿の書き出し。
#
# ここは「と思う」「かも」で濁さない。濁すと、薦めたいのか迷ってるのか
# 分からなくなって、押す理由が消える。
#
# ただし言い切るのは **買い方** についてであって、商品の良し悪しではない。
# 商品を使っていないし、値段もレビューも本文から外したので、
# 「この商品が良い」には根拠が無い。書けるのは
# 「このカテゴリーはこう選ぶ → これがその条件に合う一つ」まで。
# 型が偏ると、毎回同じ投稿に見える。
# 参考アカウントは1行目の「型」自体を変えている。
#
#   逆張り    全身クレドなんて厳しい。
#   否定      たるみは皮膚が伸びたんじゃない。
#   宣言      ナイアシンアミドはヤバい成分です。
#   絞り込み  30代後半で美容医療デビューする人、
#
# ここも型で分けて持つ。増やすときは、既存と違う型のものを足すこと。
