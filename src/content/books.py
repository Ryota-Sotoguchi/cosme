def book_benefit_for(item_name: str) -> Benefit | None:
    """書名から「どんな本か」を判定する。判定できなければ None。"""
    name = item_name or ""
    for benefit in BOOK_BENEFITS:
        if any(keyword in name for keyword in benefit.keywords):
            return benefit
    return None


def book_benefit_by_cursor(cursor: int) -> Benefit:
    return BOOK_BENEFITS[cursor % len(BOOK_BENEFITS)]


