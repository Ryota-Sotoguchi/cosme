"""剤形ごとの「言ってよい効能」と悩みの文脈。

## なぜこの形なのか

このアカウントは商品を使っていないので、特定商品について
「この商品にこういう効果があった」とは書けない（体験の捏造になる）。

一方で、化粧品には薬機法で**56項目の標ぼう可能な効能**が定められていて、
「化粧水は皮膚にうるおいを与えるもの」のような**カテゴリー一般の役割**は
そのカテゴリーの商品であれば言ってよい。

そこで、商品名から剤形（化粧水・乳液・シャンプー…）を判定し、
**その剤形に許された効能だけ**を紐づける。

  ○ 化粧水 → 皮膚にうるおいを与える     （56項目内）
  ○ トリートメント → 毛髪にはり、こしを与える（56項目内）
  × ブラシ → うるおいを与える            （剤形が対応しないので出さない）
  × 何でも → 肌荒れが治る                 （56項目外。そもそも禁止）

## 悩みの提起について

「〜でお悩みの方へ」自体は問題ないが、**不安を煽る形は禁止**。
「シミを放置すると取り返しがつかない」はNG、
「乾燥が気になる時期に見直す人が多い」はOK、という線引き。
ここでは後者の言い方だけを置く。

## 効果の断定はしない

「シワが消えていくのを実感」のような断定はNG。
「〜するためのもの」「〜タイプ」という、役割の説明にとどめる。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Benefit:
    """剤形に紐づく、言ってよい役割と悩みの文脈。"""

    id: str
    # 商品名にこの語があれば、この剤形と判定する
    keywords: tuple[str, ...]
    # 56項目の範囲内で言える役割
    role: str
    # 煽らない形の悩みの文脈
    concern: str


