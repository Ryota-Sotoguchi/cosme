# 悩みから入るフック
#
# もとの書き出しは全部「{category}＋助言」だった。
#
#   スキンケア探してる人、これ見てみてほしい👀
#
# 誰の何の話か分からないまま流れる。実測でも表示数が伸びていない。
#
# 読む人が「え、それわたしだ」と思う状況を先に置くと、
# そこで指が止まる。止まってから商品を見る。
