# 失敗の形を切り出す言い方。毎回「よくあるのが、」だと、そこが型になる。
PITFALL_LEADS: tuple[str, ...] = (
    "よくあるのが、{body}。",
    "だいたいこれで失敗する。{body}。",
    "わたしがやりがちなのは、{body}。",
    "多いのは{body}、ってやつ。",
    "ありがちなのが、{body}。",
)


def pitfall_line(benefit: Benefit, cursor: int = 0) -> str:
    """その剤形でよくある外し方を一文にする。無ければ空。"""
    body = PITFALLS.get(benefit.id, "")
    if not body:
        return ""
    return PITFALL_LEADS[cursor % len(PITFALL_LEADS)].format(body=body)
