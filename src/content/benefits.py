# 箇条書きの見出し。毎回同じだと、同じ投稿を繰り返しているように見える。
#
# 見出しっぽい見出し（「比べるときの軸」「見るのはこのへんだけ」）は
# 人が書く言い方ではないので置かない。話しかけている形にする。
TIPS_HEADINGS: tuple[str, ...] = (
    "決めるとき、だいたいここ見てる👀",
    "わたしが確認してるのはこのへん📝",
    "動く前にこれだけ見ておくとラク👀",
    "ここを外すと、だいたい後悔する📝",
    "毎回おなじところ見てる気がする💭",
    "とりあえずここを見ておけば大丈夫👀",
    "決め手にしてるのはこのあたり💭",
)


def tips_block(
    benefit: Benefit,
    heading: str | None = None,
    *,
    cursor: int = 0,
    count: int = 3,
    with_why: bool = False,
) -> str:
    """選ぶときに見るところを箇条書きで組み立てる。

    参考にした伸びている投稿が「保存したくなるチェックリスト」型だった。
    箇条書きは保存・リポストされやすい。

    ## なぜ全部を出さないのか

    剤形ごとの tips は固定なので、全部並べると同じ剤形の商品では
    毎回まったく同じ箇条書きになる。1日1本の投稿でこれをやると、
    見ている側には「同じ投稿を繰り返している」ようにしか見えない。

    そこで cursor をずらしながら count 件だけ取り出す。
    順番も変わるので、同じ剤形でも見え方が変わる。
    """
    if not benefit.tips:
        return ""
    title = heading if heading is not None else TIPS_HEADINGS[cursor % len(TIPS_HEADINGS)]

    tips = benefit.tips
    n = min(count, len(tips))
    start = cursor % len(tips)
    picked = [tips[(start + i) % len(tips)] for i in range(n)]

    if with_why:
        # 観点だけ並べても読み手には何も残らない。なぜ見るのかを添える。
        # 上限500字を使い切る型は、ここで長さを稼ぐ（水増しではなく中身）。
        notes = TIP_NOTES.get(benefit.id, {})
        lines = "\n".join(
            f"・{tip}\n　{notes[tip]}" if tip in notes else f"・{tip}"
            for tip in picked
        )
    else:
        lines = "\n".join(f"・{tip}" for tip in picked)

    # 役割の一文は毎回付けない。
    #
    # もとは benefit.role をそのまま末尾に置いていたが、
    # 「シャンプーは髪と地肌を清浄にするもの」は辞書の文で、
    # 人が投稿の最後にこう書くことはない。しかも毎回付くので、
    # 箇条書き＋定義文、という型が固定されて見えていた。
    #
    # 表示するのは line（人の言い方にしたもの）で、
    # 3回に2回だけ付ける。付かない回は箇条書きで終わる。
    if benefit.line and cursor % 3 != 2:
        return f"{title}\n\n{lines}\n\n{benefit.line}"
    return f"{title}\n\n{lines}"


def benefit_by_cursor(cursor: int) -> Benefit:
    """剤形を指定せずに1つ取り出す。

    リンクの無い投稿でもノウハウを使い回すための入口。
    乱数を使わず、カーソルで決定的に回す。
    """
    return BENEFITS[cursor % len(BENEFITS)]

