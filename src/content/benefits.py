def benefit_for(item_name: str) -> Benefit | None:
    """商品名から剤形を判定し、言ってよい効能を返す。

    判定できないもの（ブラシ・ポーチなど）は None。
    その場合は効能に触れない。無理に紐づけると、
    その剤形に許されていない効能を書くことになる。
    """
    name = item_name or ""
    for benefit in BENEFITS:
        if any(keyword in name for keyword in benefit.keywords):
            return benefit
    return None


def tips_block(benefit: Benefit, heading: str | None = None) -> str:
    """選ぶときに見るところを箇条書きで組み立てる。

    参考にした伸びている投稿が「保存したくなるチェックリスト」型だった。
    箇条書きは保存・リポストされやすい。
    """
    if not benefit.tips:
        return ""
    title = heading or "選ぶとき見てるところ👀"
    lines = "\n".join(f"・{tip}" for tip in benefit.tips)
    return f"{title}\n\n{lines}\n\n{benefit.role}"


def benefit_by_cursor(cursor: int) -> Benefit:
    """剤形を指定せずに1つ取り出す。

    リンクの無い投稿でもノウハウを使い回すための入口。
    乱数を使わず、カーソルで決定的に回す。
    """
    return BENEFITS[cursor % len(BENEFITS)]
