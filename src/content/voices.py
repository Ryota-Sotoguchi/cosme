def load_voices(path: "Path") -> dict[str, tuple[str, ...]]:
    """collect_reviews.py がためた結果を読む。

    無ければ空。**投稿は声が無くても成立する**ので、
    読めないことを失敗にしない。
    """
    import json

    if not path.exists():
        return {}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    return {
        code: tuple(entry.get("voices", []))
        for code, entry in raw.items()
        if entry.get("voices")
    }


def load_voice_counts(path: "Path") -> dict[str, dict[str, int]]:
    """商品ごとの「何件がそう言っていたか」。

    古い voices.json には counts が無い。その場合は空で返し、
    投稿側は控えめな言い方（「〜って人がいた」）を使う。
    """
    import json

    if not path.exists():
        return {}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    return {
        code: {str(k): int(v) for k, v in (entry.get("counts") or {}).items()}
        for code, entry in raw.items()
    }


def voice_phrase(voices: tuple[str, ...], *, cursor: int = 0, limit: int = 1) -> str:
    """使用感の語そのもの。文型は voice_sentence が付ける。

    2語まで。3語並べるとスペック表になって、人の言葉に見えなくなる。
    件数は出さない。こちらの集計方法に依存する数字なので、
    「何人が言った」とは書けない。
    """
    if not voices:
        return ""
    start = cursor % len(voices)
    picked = list(dict.fromkeys(
        voices[(start + i) % len(voices)] for i in range(min(max(1, limit), len(voices)))
    ))
    if len(picked) == 1:
        return picked[0]
    # 「伸びがいいし、べたつかない」。並列の「、」より会話に近い。
    # ただし「し」が付けられるのは活用する語尾だけ。
    # 「しっとり」は副詞なので「しっとりし、」にすると壊れる。
    return f"{picked[0]}{_joiner(picked[0])}{picked[1]}"


def _joiner(word: str) -> str:
    """前の語に合う繋ぎ。活用しない語に「し」を付けない。"""
    return "し、" if word.endswith(("い", "る", "た")) else "、"


# ----------------------------------------------------------------------
# 誰の感想なのかを言う文型
#
# ## なぜ出典を言うのか
#
# 一度は「地の文に溶かす」方針で出典を外していた（2026-08-31）。
# その結果できるのは「べたつかないタイプ」という、**誰の感想か分からない
# 文**で、読み手にはこちらが使ったように読める。使っていないので、それは
# 事実と違う。
#
# 出典を言っても硬くならない。人がふだん書くのはこの形。
#
#     ×  レビューによると、べたつかないという評価が多いようです
#     ○  べたつかないって書いてる人が多かった
#
# しかも「使った人がそう言っている」ほうが、こちらの感想より強い。
# 使っていない人間の「いいと思う」には根拠が無いが、
# 何百人が同じことを書いているのは事実として重い。
#
# ## 何を言わないか
#
# 「効果があった」系は voices.py の時点で拾っていない（薬機法）。
# ここで扱えるのはテクスチャ・香り・使い勝手だけ。
# ----------------------------------------------------------------------
# 「多い」と言い切れるだけの件数があるときの言い方
VOICE_FRAMES: tuple[str, ...] = (
    "{v}って書いてる人が多かった",
    "レビュー見てると{v}って声が多い",
    "使ってる人は{v}って言ってる",
    "{v}っていう感想をよく見かけた",
    "感想で目立つのは{v}ってところ",
    "{v}って書かれてることが多い",
)

# 数件しか言っていないときの言い方。
# 2件を「多い」と書くのは、こちらの都合で数を大きく見せることになる。
FEW_VOICE_FRAMES: tuple[str, ...] = (
    "{v}って書いてる人がいた",
    "{v}っていう感想があった",
    "{v}らしい",
    "使った人の言葉だと{v}",
    "{v}って書いてる人もいる",
)

# これ以上の件数が同じことを言っていれば「多い」と書いてよい
MANY_THRESHOLD = 5


def voice_sentence(
    voices: tuple[str, ...],
    *,
    cursor: int = 0,
    limit: int = 2,
    counts: dict[str, int] | None = None,
) -> str:
    """使った人の感想を、誰の感想か分かる形で一文にする。

    counts を渡すと、件数に応じて言い方を変える。
    2件しか言っていないものを「多かった」と書くと、
    こちらの都合で数を大きく見せることになる。

    材料が無ければ空。**声が無くても投稿は成立する。**
    """
    phrase = voice_phrase(voices, cursor=cursor, limit=limit)
    if not phrase:
        return ""

    # 件数が分からないときも控えめな言い方にする。
    # 「多かった」は根拠がある場合にだけ書く。
    used = [w for w in voices if w in phrase]
    weakest = min(((counts or {}).get(w, 0) for w in used), default=0)
    frames = VOICE_FRAMES if weakest >= MANY_THRESHOLD else FEW_VOICE_FRAMES
    return frames[cursor % len(frames)].format(v=phrase)
